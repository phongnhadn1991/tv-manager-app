const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('tvAPI', {
  connect: (ip, port) => ipcRenderer.invoke('adb:connect', ip, port),
  disconnect: () => ipcRenderer.invoke('adb:disconnect'),
  getDeviceInfo: () => ipcRenderer.invoke('adb:deviceInfo'),
  listPackages: () => ipcRenderer.invoke('adb:listPackages'),
  getPackageInfo: (pkg) => ipcRenderer.invoke('adb:packageInfo', pkg),
  disablePackage: (pkg) => ipcRenderer.invoke('adb:disable', pkg),
  enablePackage: (pkg) => ipcRenderer.invoke('adb:enable', pkg),
  forceStop: (pkg) => ipcRenderer.invoke('adb:forceStop', pkg),
  screenshot: () => ipcRenderer.invoke('adb:screenshot'),
  sendKey: (keycode) => ipcRenderer.invoke('adb:sendKey', keycode),
  installApk: (apkPath) => ipcRenderer.invoke('adb:installApk', apkPath),
  backup: () => ipcRenderer.invoke('adb:backup'),
  restore: (disabledList) => ipcRenderer.invoke('adb:restore', disabledList),
  selectApkFile: () => ipcRenderer.invoke('dialog:selectApk'),
  saveBackupFile: (data) => ipcRenderer.invoke('dialog:saveBackup', data),
  loadBackupFile: () => ipcRenderer.invoke('dialog:loadBackup'),
  buildLauncher: () => ipcRenderer.invoke('launcher:build'),
  launcherStatus: () => ipcRenderer.invoke('launcher:status'),
  getThemes: () => ipcRenderer.invoke('launcher:themes'),
  applyTheme: (name) => ipcRenderer.invoke('launcher:applyTheme', name),
  uploadWallpaper: (filePath) => ipcRenderer.invoke('launcher:uploadWallpaper', filePath),
  removeWallpaper: () => ipcRenderer.invoke('launcher:removeWallpaper'),
  selectImage: () => ipcRenderer.invoke('dialog:selectImage'),
  getLeanbackApps: () => ipcRenderer.invoke('launcher:getLeanbackApps'),
  getTvConfig: () => ipcRenderer.invoke('launcher:getTvConfig'),
  saveDock: (dockApps) => ipcRenderer.invoke('launcher:saveDock', dockApps),
  getDebloatList: () => ipcRenderer.invoke('cleaner:debloatList'),
  batchDisable: (pkgs) => ipcRenderer.invoke('cleaner:batchDisable', pkgs),
});
